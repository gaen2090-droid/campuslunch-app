///
/// 관공서 공휴일 기준이며 근로자의 날(5/1)은 포함하지 않는다.
/// 해마다 인사혁신처 월력요항을 확인해 다음 해 목록을 추가해야 한다.
/// 목록에 없는 해에는 공휴일이 없는 것으로 취급한다(= 요일 휴무만 적용).
library;

