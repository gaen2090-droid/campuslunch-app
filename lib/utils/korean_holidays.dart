  '2026-10-03', '2026-10-05',
  '2026-10-09',
  '2026-12-25',
};

bool isKoreanPublicHoliday(DateTime d) {
  final key =
      '${d.year.toString().padLeft(4, '0')}-${d.month.toString().padLeft(2, '0')}-${d.day.toString().padLeft(2, '0')}';
  return kKoreanPublicHolidays.contains(key) || _kHolidays2026.contains(key);
}
